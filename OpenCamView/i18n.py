MODE = 'system'

def set_language(mode):
    global MODE
    if mode not in ('system', 'pl', 'en'):
        raise ValueError('Unsupported language')
    MODE = mode

def get_language():
    if MODE != 'system':
        return MODE
    try:
        from Components.Language import language
        system_code = language.getLanguage()
        return 'pl' if str(system_code).lower().startswith('pl') else 'en'
    except (ImportError, AttributeError, TypeError):
        return 'pl'

def tr(value):
    return EN.get(value, value) if get_language() == 'en' else value
